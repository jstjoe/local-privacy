"""Built-in label vocabularies: raw label (as a detector emits it or a dataset
annotates it) -> canonical label (see `labels.py`).

One dict per source. Map each raw label to the *most specific* canonical label
it unambiguously denotes; fall back to the coarse category when a raw label
spans several sub-types (e.g. OPF's `account_number`) or its sub-type is
unclear (e.g. ai4privacy's `ACCOUNTNUM`).

Entry order is significant for two derived lists — GLiNER prompt order and
Skyflow request-type order — so entries are grouped by coarse category in
`COARSE_LABELS` order. Keep new entries inside their category's block.

Adding a vocabulary for a new detector or dataset doesn't require editing this
file: call `opf_eval.taxonomy.register_vocab(key, {...})` at runtime.
"""

